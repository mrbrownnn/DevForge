"""Turning a counterexample into a permanent regression test.

The point of the corpus is that DevForge should not rediscover the same failure next
month. The path from one to the other is::

    counterexample -> reproduction -> regression test -> repair -> permanent suite

This module writes the middle step. It produces test *source*; it does not install it
into the project's suite. That distinction is the same one the adversarial strategy
observes: the falsifier proposes, the workflow disposes. Writing into someone's
permanent test suite without a decision is exactly the silent modification the repair
verifiers exist to catch.

Generated tests are honest about being incomplete. Where the counterexample records
what actually happened but not what *should* have happened - which is most of the
time, because the whole reason the bug exists is that nobody stated the expectation -
the test carries an explicit failing assertion rather than a plausible-looking one.
A regression test that passes without checking anything is worse than no test.
"""

from __future__ import annotations

from pathlib import Path

from devforge.falsification.models import Counterexample, StrategyName, TestWeakness

HEADER = '"""Regression test generated by DevForge falsification.\n\n{description}\n"""'


def render_regression_test(example: Counterexample) -> str:
    """A pytest module reproducing one counterexample."""
    description = "\n".join(
        [
            f"Finding:    {example.finding_id}",
            f"Strategy:   {example.strategy.value}",
            f"Target:     {example.target}",
            f"Discovered: {example.discovered_at.isoformat()}",
            "",
            f"Input:    {_trim(example.minimal_input)}",
            f"Expected: {_trim(example.expected)}",
            f"Actual:   {_trim(example.actual)}",
            "",
            "Reproduction: " + (" ".join(example.reproduction) or "(not recorded)"),
        ]
    )

    body = _body_for(example)
    return f"{HEADER.format(description=description)}\n\n{body}\n"


def _body_for(example: Counterexample) -> str:
    name = _test_name(example)

    if example.strategy is StrategyName.ADVERSARIAL:
        # The adversarial strategy already produced a runnable test; the input field
        # holds it. Reproducing it verbatim is more faithful than paraphrasing.
        return (
            "# The falsifier's original generated test, preserved verbatim.\n"
            f"{example.input}\n"
        )

    if example.strategy is StrategyName.DIFFERENTIAL:
        return "\n".join(
            [
                f"def {name}():",
                "    # The new implementation diverged from the old one on this input.",
                f"    # Old: {_trim(example.expected, 200)}",
                f"    # New: {_trim(example.actual, 200)}",
                f"    # Reproduce with: {' '.join(example.reproduction)}",
                "    raise AssertionError(",
                '        "restate the expected behaviour here, then assert it"',
                "    )",
            ]
        )

    module = example.file.replace("/", ".").removesuffix(".py") if example.file else ""
    lines = [f"def {name}():"]
    if module and example.symbol:
        lines.extend(
            [
                f"    from {module} import {example.symbol}",
                "",
                f"    # Input that falsified the implementation: {_trim(example.input, 120)}",
                f"    # Expected: {_trim(example.expected, 120)}",
                f"    # Actual:   {_trim(example.actual, 120)}",
                "    raise AssertionError(",
                '        "call the symbol with the recorded input and assert the "',
                '        "expected behaviour"',
                "    )",
            ]
        )
    else:
        lines.extend(
            [
                f"    # Input:    {_trim(example.input, 120)}",
                f"    # Expected: {_trim(example.expected, 120)}",
                f"    # Actual:   {_trim(example.actual, 120)}",
                "    raise AssertionError(",
                '        "reproduce the recorded input and assert the expected behaviour"',
                "    )",
            ]
        )
    return "\n".join(lines)


def render_weakness_test(weakness: TestWeakness) -> str:
    """A test skeleton for a surviving mutant.

    A weakness is not a bug: the code may be right and the check missing. So this
    produces the check the suite lacks, phrased as what nobody is asserting.
    """
    description = "\n".join(
        [
            f"Finding: {weakness.finding_id}",
            f"Mutant:  {weakness.mutant_id} ({weakness.operator})",
            f"Site:    {weakness.file}:{weakness.line}",
            "",
            weakness.unchecked_behavior,
            "",
            "This is a gap in the tests, not necessarily a defect in the code.",
        ]
    )
    body = weakness.proposed_test or (
        f"def test_{Path(weakness.file).stem}_line_{weakness.line}():\n"
        "    raise AssertionError('write the missing assertion')\n"
    )
    return f"{HEADER.format(description=description)}\n\n{body}\n"


def write_regression_test(
    example: Counterexample, *, directory: Path, filename: str = ""
) -> Path:
    """Write the generated test to ``directory`` and return the path.

    The caller chooses the directory, which is how "propose" stays distinct from
    "install": nothing here decides that the project's test suite is the target.
    """
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / (filename or f"test_regression_{example.finding_id}.py")
    path.write_text(render_regression_test(example), encoding="utf-8")
    return path


def _test_name(example: Counterexample) -> str:
    stem = example.symbol or Path(example.file).stem or example.strategy.value
    slug = "".join(char if char.isalnum() else "_" for char in stem).strip("_").lower()
    return f"test_regression_{slug or 'counterexample'}_{example.finding_id.split('_')[-1]}"


def _trim(text: str, limit: int = 400) -> str:
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 3] + "..."
